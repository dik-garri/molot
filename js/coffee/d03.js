// День 3 — За то, что мы — Божьи дети (Ин 1:12, Гал 4:4–5). Образ: большая чашка и маленькая детская
// на одном блюдце; маленькая прижалась к боку большой, её пар тянется к пару большой — и они сходятся в сердечко.
COFFEE_ART[3] = (K, C) => {
  const { WC, cup, heart } = C;
  let s = K.ring(268, 222, 30, .38);
  // общее блюдце
  s += K.W(`<ellipse cx="160" cy="232" rx="122" ry="15"/>`, WC.c1, .55);
  // большая чашка: ручка влево
  s += cup(K, 132, 142, 120, { dir: -1, saucer: false });
  // тень маленькой на боку большой
  s += K.Wf(`<ellipse cx="196" cy="214" rx="16" ry="18"/>`, WC.c2, .35);
  // маленькая детская чашка: прижалась к большой и чуть наклонилась к ней
  s += `<g transform="rotate(-9 214 228)"><path d="M186,188 L242,188 C242,219.4 230.8,228.3 214,228.3 C197.2,228.3 186,219.4 186,188Z" fill="${WC.paper}"/>` + cup(K, 214, 188, 56, { dir: 1, saucer: false }) + `</g>`;
  // край блюдца тушью
  s += K.I(`<path d="M42,236 Q160,260 280,233"/>`, 1.25);
  // пар: у большой — спокойные длинные струйки, у маленькой — тянется к большой
  const big = ["M110,128 c-8,-14 8,-24 0,-38 c-5,-10 4,-16 1,-24", "M136,126 c-8,-14 8,-24 0,-36 c-4,-8 2,-14 2,-20"];
  const small = "M208,174 c-6,-10 4,-16 -2,-26 C200,124 168,118 156,102 C150,94 146,86 140,80";
  s += K.Ws(big.join(" ") + " " + small, WC.c1, 7, .22);
  s += K.I(big.map(d => `<path d="${d}"/>`).join("") + `<path d="${small}"/>`, 1.15);
  // сердечко там, где пар сошёлся
  s += K.Wf(`<path d="${heart(140, 68, 26)}"/>`, WC.c2, .75);
  s += K.I(`<path transform="translate(1.4,-1.2)" d="${heart(140, 68, 26)}"/>`, 1.15);
  s += K.splat(3, 9, 36, 60, 296, 262, WC.c2);
  return `<g transform="translate(6,4)">${s}</g>`;
};
