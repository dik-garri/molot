// День 14 — За благодать (Ин 1:16–17, «благодать на благодать»). Образ: из турки льётся кофе в уже полную чашку —
// он переливается через край, наполняет блюдце и растекается по бумаге. Полнота, которой больше, чем вмещается.
COFFEE_ART[14] = (K, C) => {
  const { WC, f } = C;
  const x = 138, y = 158, w = 118, h = w * .72;            // чашка: центр ободка, ширина, высота
  const L = x - w / 2, R = x + w / 2, bot = y + h;
  let s = "";
  // лужа под блюдцем — кофе ушёл и за край блюдца
  s += K.B(`<ellipse cx="${x - 4}" cy="${f(bot + 12)}" rx="106" ry="19"/><ellipse cx="${x + 84}" cy="${f(bot + 20)}" rx="24" ry="8"/>`, WC.c1, .5);
  s += K.W(`<ellipse cx="${x + 92}" cy="${f(bot + 20)}" rx="14" ry="4.5"/><ellipse cx="${x - 100}" cy="${f(bot + 14)}" rx="8" ry="3"/>`, WC.c2, .42);
  // блюдце и кофе в нём до краёв
  s += K.W(`<ellipse cx="${x}" cy="${f(bot + 3)}" rx="${f(w * .8)}" ry="${f(w * .14)}"/>`, WC.c1, .55);
  s += K.W(`<ellipse cx="${x - 2}" cy="${f(bot + 4)}" rx="${f(w * .68)}" ry="${f(w * .095)}"/>`, WC.c2, .55);
  // ручка, тело чашки, тень
  const body = `M${f(L)},${f(y)} L${f(R)},${f(y)} C${f(R)},${f(y + h * .78)} ${f(x + w * .3)},${f(bot)} ${f(x)},${f(bot)} C${f(x - w * .3)},${f(bot)} ${f(L)},${f(y + h * .78)} ${f(L)},${f(y)}Z`;
  const shade = `M${f(x + w * .14)},${f(y)} L${f(R)},${f(y)} C${f(R)},${f(y + h * .78)} ${f(x + w * .32)},${f(bot)} ${f(x + w * .1)},${f(bot)}Z`;
  const handle = `M${f(x + w * .46)},${f(y + h * .16)} C${f(x + w * .8)},${f(y + h * .06)} ${f(x + w * .82)},${f(y + h * .66)} ${f(x + w * .33)},${f(y + h * .76)}`;
  s += K.Ws(handle, WC.c1, w * .09, .6);
  s += K.W(`<path d="${body}"/>`, WC.c1, .4);
  s += K.W(`<path d="${shade}"/>`, WC.c2, .3);
  // кофе горкой над ободком
  const dome = `M${f(L - 4)},${f(y + 2)} C${f(L + 4)},${f(y - 24)} ${f(R - 4)},${f(y - 24)} ${f(R + 4)},${f(y + 2)} C${f(R - 10)},${f(y + 13)} ${f(L + 10)},${f(y + 13)} ${f(L - 4)},${f(y + 2)}Z`;
  s += K.W(`<path d="${dome}"/>`, WC.c3, .82);
  // блик-мениск белилами
  s += K.Ws(`M${f(L + 20)},${f(y - 4)} C${f(L + 32)},${f(y - 9)} ${f(x - 12)},${f(y - 11)} ${f(x)},${f(y - 11)}`, WC.white, 3.5, .8);
  // потёки по стенке: разной длины, сужаются книзу
  const drip = (x0, y0, len, wd, bend) => {
    const x1 = x0 + bend, y1 = y0 + len;
    return `<path d="M${f(x0 - wd)},${f(y0)} C${f(x0 - wd * .7)},${f(y0 + len * .5)} ${f(x1 - wd * .5)},${f(y1 - len * .3)} ${f(x1 - wd * .45)},${f(y1)} A${f(wd * .5)},${f(wd * .55)} 0 0 0 ${f(x1 + wd * .45)},${f(y1)} C${f(x1 + wd * .5)},${f(y1 - len * .3)} ${f(x0 + wd * .7)},${f(y0 + len * .5)} ${f(x0 + wd)},${f(y0)}Z"/>`;
  };
  // перелив по всему ободку: волнистая полоса снаружи, из неё свисают потёки
  s += K.Wf(`<path d="M${f(L - 3)},${f(y)} C${f(L + 20)},${f(y + 12)} ${f(R - 20)},${f(y + 12)} ${f(R + 3)},${f(y)} L${f(R)},${f(y + 7)} Q${f(R - 14)},${f(y + 13)} ${f(x + 30)},${f(y + 15)} Q${f(x + 8)},${f(y + 22)} ${f(x - 10)},${f(y + 16)} Q${f(x - 36)},${f(y + 20)} ${f(L + 8)},${f(y + 12)} Q${f(L)},${f(y + 9)} ${f(L - 3)},${f(y)}Z"/>`, WC.c3, .55);
  s += K.Wf(drip(L + 6, y + 3, 40, 4.5, 3) + drip(x - 26, y + 9, 64, 4, -2) + drip(x + 20, y + 9, 30, 3.2, 1) + drip(R - 8, y + 4, 52, 4.2, -5), WC.c3, .62);
  // струя из турки: широкая у носика, сужается к чашке
  const stream = `M204,99 C185,100 158,114 ${f(x + 16)},${f(y - 12)} L${f(x + 10)},${f(y - 12)} C${f(151)},${f(118)} 180,109 203,108Z`;
  s += K.Wf(`<path d="${stream}"/>`, WC.c3, .85);
  s += K.I(`<path d="M203,100 C184,101 158,113 ${f(x + 17)},${f(y - 14)}"/>`, .8);
  // всплеск там, где струя входит в кофе
  s += K.Wf(`<circle cx="${f(x + 2)}" cy="${f(y - 20)}" r="2"/><circle cx="${f(x + 25)}" cy="${f(y - 22)}" r="1.6"/><circle cx="${f(x + 8)}" cy="${f(y - 28)}" r="1.3"/><circle cx="${f(x + 30)}" cy="${f(y - 15)}" r="1.4"/>`, WC.c3, .8);
  // турка, наклонённая над чашкой (ручка уходит вверх-вправо)
  const cz = `M-18,0 C-14,6 -13,8 -13,12 C-14,24 -22,34 -22,44 Q-22,49 -16,49 L16,49 Q22,49 22,44 C22,34 14,24 13,12 C13,8 14,6 18,0 Z`;
  let t = `<g transform="translate(226,86) rotate(-45) scale(1.15)">`;
  t += K.W(`<path d="${cz}"/>`, WC.c2, .5) + K.W(`<path d="M3,12 C8,24 15,34 15,46 L19,48 C23,40 19,28 12,12Z"/>`, WC.c3, .3);
  t += K.Ws(`M14,15 C28,15 42,17 54,19`, WC.c3, 5, .65);
  t += K.I(`<g transform="translate(1.4,-1.2)"><path d="${cz}"/><ellipse cx="0" cy="0" rx="18" ry="4.5"/><path d="M-18,0 Q-24,-1 -26,-4"/>` +
    `<path d="M13,13 C27,13 41,15 54,17 M13,17 C27,17 41,19 54,21 M54,17 Q57,19 54,21"/><path d="M-12,20 h24" stroke-width=".8"/></g>`, 1.2);
  t += `</g>`;
  s += t;
  // контуры чашки и блюдца тушью — со сдвигом от размывки
  const bodyOpen = `M${f(R)},${f(y)} C${f(R)},${f(y + h * .78)} ${f(x + w * .3)},${f(bot)} ${f(x)},${f(bot)} C${f(x - w * .3)},${f(bot)} ${f(L)},${f(y + h * .78)} ${f(L)},${f(y)}`;
  s += K.I(`<g transform="translate(1.6,-1.4)"><path d="${bodyOpen}"/>` +
    `<path d="M${f(L - 3)},${f(y + 1)} C${f(L + 4)},${f(y - 23)} ${f(R - 4)},${f(y - 23)} ${f(R + 3)},${f(y + 1)}"/><path d="${handle}"/>` +
    `<path d="M${f(x - w * .8)},${f(bot + 3)} C${f(x - w * .6)},${f(bot + w * .17)} ${f(x + w * .6)},${f(bot + w * .17)} ${f(x + w * .82)},${f(bot + 2)}"/>` +
    `<path d="M${f(x - w * .8)},${f(bot + 3)} C${f(x - w * .7)},${f(bot - 4)} ${f(x - w * .5)},${f(bot - 6)} ${f(x - w * .42)},${f(bot - 6)}"/>` +
    `<path d="M${f(x + w * .82)},${f(bot + 2)} C${f(x + w * .72)},${f(bot - 4)} ${f(x + w * .5)},${f(bot - 6)} ${f(x + w * .42)},${f(bot - 6)}"/></g>`, 1.3);
  // капли, срывающиеся с края блюдца, и брызги
  s += K.Wf(`<path d="${C.drop(x + 100, bot + 6, 9)}"/><path d="${C.drop(x - 100, bot + 4, 7)}"/>`, WC.c3, .65);
  s += K.splat(14, 9, 30, 70, 300, 268, WC.c2);
  return s;
};
