// День 12 — За победу над смертью (1 Кор 15:55, 57; 2 Тим 1:10). Образ: кофейное зерно, положенное в землю,
// не пропало — из него пробился росток; над ним встаёт солнце. Смерть не последнее слово, за ней — жизнь.
COFFEE_ART[12] = (K, C) => {
  const { WC, f } = C;
  const sx = 160, sy = 196;
  // рассвет: мягкое небо, восходящее солнце и лучи
  let s = K.B(`<ellipse cx="${sx}" cy="${sy - 10}" rx="140" ry="62"/>`, WC.c1, .28);
  s += K.W(`<circle cx="${sx}" cy="${sy}" r="54"/>`, WC.c1, .55);
  s += K.B(`<circle cx="${sx}" cy="${sy + 6}" r="30"/>`, WC.white, .6);
  let rays = "", strokes = "";
  for (let a = -168; a <= -12; a += 13) {
    const r = a * Math.PI / 180, c = Math.cos(r), n = Math.sin(r);
    rays += `<path d="M${f(sx + c * 64)},${f(sy + n * 64)} L${f(sx + c * (a % 2 ? 80 : 88))},${f(sy + n * (a % 2 ? 80 : 88))}"/>`;
    strokes += `M${f(sx + c * 66)},${f(sy + n * 66)} L${f(sx + c * 112)},${f(sy + n * 112)} `;
  }
  s += K.Ws(strokes, WC.c1, 3.2, .35);
  s += K.I(`<g transform="translate(1.4,-1.2)"><path d="M${sx - 54},${sy} A54,54 0 0 1 ${sx + 54},${sy}"/></g>` + rays, 1.05);
  // земля в разрезе
  const top = `M22,201 Q46,194 74,199 T132,197 T200,200 T258,196 T298,200`;
  const soil = `${top} C306,216 305,244 292,256 Q160,270 30,258 C15,246 14,218 22,201Z`;
  s += K.W(`<path d="${soil}"/>`, WC.c2, .45) + K.B(`<path d="M24,228 Q160,218 296,228 V252 Q160,262 24,252Z"/>`, WC.c3, .22);
  s += K.Wf(`<ellipse cx="58" cy="244" rx="6" ry="3.5"/><ellipse cx="250" cy="214" rx="5" ry="3"/><ellipse cx="272" cy="246" rx="7" ry="4"/><ellipse cx="92" cy="216" rx="4" ry="2.5"/>`, WC.c3, .5);
  s += K.I(`<g transform="translate(1.2,-1)"><path d="${top}"/></g>`, 1);
  // светлая лунка вокруг зерна, чтобы оно читалось
  s += K.B(`<ellipse cx="${sx}" cy="238" rx="34" ry="24"/>`, WC.paper, .6);
  // кофейное зерно: овал с S-бороздкой, чуть наклонён
  const bean = `<ellipse cx="0" cy="0" rx="22" ry="15"/>`, crease = `M-19,1 C-8,-8 6,8 19,-1`;
  s += `<g transform="translate(158,236) rotate(-24)">` + K.W(bean, WC.c3, .8) + K.Wf(`<path d="M-16,-3 C-10,-12 6,-14 14,-8 C4,-9 -6,-8 -16,-3Z"/>`, WC.white, .4) +
    K.Ws(crease, WC.c1, 2.6, .9) + K.I(`<g transform="translate(1.2,-1)">${bean}<path d="${crease}"/></g>`, 1.2) + `</g>`;
  // корешки — тонкие, в разные стороны
  s += K.I(`<path d="M161,250 C163,256 156,260 159,268"/><path d="M160,256 c-6,1 -9,5 -15,4"/><path d="M161,260 c5,0 8,3 13,2"/><path d="M150,264 l-4,-1"/>`, .8);
  // росток: стебель из зерна и два листа кофейного дерева
  const stem = `M158,222 C152,204 166,186 160,150`;
  s += `<g transform="translate(158,222) scale(1.15) translate(-158,-222)">` + K.Ws(stem, WC.c2, 4.5, .75);
  const leafL = `M${sx},156 C${sx - 8},140 ${sx - 28},128 ${sx - 52},132 C${sx - 40},150 ${sx - 18},162 ${sx},156Z`;
  const leafR = `M${sx},152 C${sx + 10},134 ${sx + 32},120 ${sx + 54},124 C${sx + 44},144 ${sx + 20},158 ${sx},152Z`;
  s += K.W(`<path d="${leafL}"/><path d="${leafR}"/>`, WC.c2, .66);
  s += K.Wf(`<path d="M${sx - 48},133 C${sx - 30},134 ${sx - 12},146 ${sx},156 C${sx - 18},152 ${sx - 34},146 ${sx - 48},133Z"/><path d="M${sx + 50},125 C${sx + 32},128 ${sx + 14},140 ${sx},152 C${sx + 18},146 ${sx + 34},138 ${sx + 50},125Z"/>`, WC.c3, .35);
  s += K.Wf(`<path d="M${sx},146 c-4,-6 -2,-12 2,-14 c3,4 2,10 -2,14Z"/>`, WC.c2, .85);
  s += K.I(`<g transform="translate(1.3,-1.1)"><path d="${stem}"/><path d="${leafL}"/><path d="${leafR}"/>` +
    `<path d="M${sx - 2},155 Q${sx - 24},140 ${sx - 48},133"/><path d="M${sx + 2},151 Q${sx + 26},134 ${sx + 50},125"/><path d="M${sx},146 c-4,-6 -2,-12 2,-14 c3,4 2,10 -2,14"/></g>`, 1.1) + `</g>`;
  // травинки по краям и птицы в рассветном небе
  s += K.I(`<path d="M40,198 l-3,-8 M44,198 l2,-9 M276,197 l-2,-8 M281,197 l3,-7"/>` +
    `<path d="M74,100 q5,-5 10,0 q5,-5 10,0"/><path d="M98,86 q4,-4 8,0 q4,-4 8,0"/><path d="M228,90 q5,-5 10,0 q5,-5 10,0"/>`, 1.1);
  s += K.splat(12, 3, 40, 70, 290, 110, WC.c2, 1.6);
  return s;
};
