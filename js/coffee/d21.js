// День 21 — За то, что Иисус — путь (Ин 14:6). Образ: тропинка, выложенная кофейными зёрнами, ведёт между холмов
// к свету на горизонте; зёрна-шаги уменьшаются вдаль.
COFFEE_ART[21] = (K, C) => {
  const { WC, f } = C;
  let s = "";
  const hy = 134;
  // свет на горизонте
  s += K.B(`<ellipse cx="160" cy="${hy}" rx="78" ry="54"/>`, WC.c1, .28);
  s += K.B(`<circle cx="160" cy="${hy}" r="34"/>`, WC.white, 1);
  s += K.Wf(`<path d="M134,${hy} A26,26 0 0 1 186,${hy}Z"/>`, WC.white, 1);
  let rays = "";
  for (let i = 0; i < 11; i++) {
    const a = Math.PI + (i + .5) * Math.PI / 11, r0 = 34, r1 = i % 2 ? 50 : 62;
    rays += `<path d="M${f(160 + Math.cos(a) * r0)},${f(hy + Math.sin(a) * r0)} L${f(160 + Math.cos(a) * r1)},${f(hy + Math.sin(a) * r1)}"/>`;
  }
  s += K.I(`<path d="M134,${hy} A26,26 0 0 1 186,${hy}"/>` + rays, 1.1);
  // холмы: дальние светлые, ближние темнее
  s += K.W(`<path d="M26,${hy + 6} C56,${hy - 12} 98,${hy - 8} 138,${hy + 2} C110,${hy + 12} 60,${hy + 16} 26,${hy + 6}Z"/>`, WC.c1, .4);
  s += K.W(`<path d="M182,${hy + 2} C222,${hy - 12} 268,${hy - 14} 296,${hy + 2} C262,${hy + 16} 214,${hy + 12} 182,${hy + 2}Z"/>`, WC.c1, .4);
  s += K.W(`<path d="M16,154 C60,140 110,146 150,160 C128,190 112,226 100,266 C72,258 44,270 18,258 C14,220 14,186 16,154Z"/>`, WC.c1, .5);
  s += K.W(`<path d="M304,154 C260,140 210,146 170,160 C192,190 208,226 220,266 C248,258 276,270 302,258 C306,220 306,186 304,154Z"/>`, WC.c1, .5);
  s += K.W(`<path d="M16,200 C44,188 80,194 112,206 C104,226 98,246 96,268 C70,262 44,272 18,262Z"/>`, WC.c2, .38);
  s += K.W(`<path d="M304,200 C276,188 240,194 208,206 C216,226 222,246 224,268 C250,262 276,272 302,262Z"/>`, WC.c2, .38);
  s += K.I(`<path d="M28,${hy + 5} C56,${hy - 12} 98,${hy - 8} 140,${hy + 3}"/><path d="M180,${hy + 3} C222,${hy - 12} 268,${hy - 14} 294,${hy + 1}"/>` +
    `<path d="M18,153 C60,141 110,147 150,161" stroke-dasharray="30 5 40 6"/><path d="M302,153 C260,141 210,147 170,161" stroke-dasharray="40 6 26 5"/>` +
    `<path d="M18,199 C44,189 80,195 112,207"/><path d="M302,199 C276,189 240,195 208,207"/>` +
    `<path d="M60,236 q8,-3 14,0 M244,240 q8,-3 14,0 M70,180 q6,-2 10,0 M236,182 q6,-2 10,0" stroke-width=".8"/>`, 1.1);
  // тропинка — светлая лента, сужается к горизонту
  const road = `M100,274 C112,236 150,212 150,186 C150,166 156,146 158,${hy + 1} L162,${hy + 1} C164,146 168,166 172,186 C176,214 200,238 226,274Z`;
  s += K.W(`<path d="${road}"/>`, WC.white, .9);
  // зёрна по тропинке: кривая от низа к горизонту, масштаб уменьшается
  const P = t => { const u = 1 - t; return [u * u * u * 162 + 3 * u * u * t * 150 + 3 * u * t * t * 162 + t * t * t * 160, u * u * u * 266 + 3 * u * u * t * 208 + 3 * u * t * t * 170 + t * t * t * (hy + 4)]; };
  let beansW = "", beansI = "";
  const ts = [0, .14, .27, .39, .5, .6, .69, .77, .84, .9, .95];
  ts.forEach((t, i) => {
    const [x, y] = P(t), sc = 1 - t * .82, side = i % 2 ? 1 : -1, ox = side * 8 * sc, rot = side * 24 + 8;
    const rx = 9 * sc, ry = 6 * sc;
    beansW += `<ellipse cx="${f(x + ox)}" cy="${f(y)}" rx="${f(rx)}" ry="${f(ry)}" transform="rotate(${rot} ${f(x + ox)} ${f(y)})"/>`;
    beansI += `<g transform="translate(${f(x + ox + 1)},${f(y - 1)}) rotate(${rot})"><ellipse rx="${f(rx)}" ry="${f(ry)}"/>` +
      `<path d="M${f(-rx * .8)},0 C${f(-rx * .3)},${f(-ry * .6)} ${f(rx * .3)},${f(ry * .6)} ${f(rx * .8)},0"/></g>`;
  });
  s += K.Wf(beansW, WC.c3, .75);
  s += K.I(beansI, 1);
  // птицы летят к свету
  s += K.I(`<path d="M206,84 q5,-5 10,0 q5,-5 10,0"/><path d="M228,66 q4,-4 8,0 q4,-4 8,0"/>`, 1.1);
  s += K.splat(21, 8, 30, 60, 300, 120, WC.c2);
  return s;
};
