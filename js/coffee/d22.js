// День 22 — За покой во Христе (Мф 11:28–29). Образ: буря в чашке утихла — гладкая, как зеркало,
// поверхность кофе, в ней отражается вечерний месяц; один тихий завиток пара; рядом сложенный плед.
COFFEE_ART[22] = (K, C) => {
  const { WC, f } = C;
  let s = "";
  // вечерний свет: тёплое растёкшееся пятно за чашкой
  s += K.B(`<circle cx="206" cy="122" r="66"/>`, WC.c1, .24);
  // месяц
  const moon = `M250,60 A22,22 0 1 0 268,96 A17,17 0 1 1 250,60Z`;
  s += K.Wf(`<path d="${moon}"/>`, WC.c1, .75);
  s += K.I(`<g transform="translate(1.2,-1)"><path d="${moon}"/></g>`, 1.1);
  s += `<path d="${C.star4(220, 70, 5)}" fill="${WC.c2}" opacity=".6"/><path d="${C.star4(286, 112, 3.6)}" fill="${WC.c2}" opacity=".5"/>`;

  // сложенный плед: два пухлых слоя, полосы у края и бахрома
  const lay = (y0, x0, x1, th) => `M${x0 + 6},${y0} Q${f((x0 + x1) / 2)},${y0 - 4} ${x1 - 4},${y0 + 1} Q${x1 + 4},${f(y0 + th / 2)} ${x1 - 3},${y0 + th} Q${f((x0 + x1) / 2)},${y0 + th + 3} ${x0 + 4},${y0 + th - 1} Q${x0 - 5},${f(y0 + th / 2)} ${x0 + 6},${y0}Z`;
  const L1 = lay(230, 24, 128, 28), L2 = lay(206, 32, 120, 26);
  s += K.W(`<path d="${L1}"/>`, WC.c1, .55) + K.W(`<path d="${L2}"/>`, WC.c1, .4);
  s += K.W(`<path d="M28,248 Q76,254 126,248 L124,257 Q76,262 30,257Z"/>`, WC.c2, .3);
  // полосы
  s += K.Ws(`M52,206 Q50,218 52,230`, WC.c2, 6, .45) + K.Ws(`M64,205 Q62,218 64,230`, WC.c2, 3, .4);
  s += K.Ws(`M44,230 Q42,244 44,256`, WC.c2, 6, .45) + K.Ws(`M56,230 Q54,244 56,257`, WC.c2, 3, .4);
  s += K.I(`<g transform="translate(1.2,-1)"><path d="${L1}"/><path d="${L2}"/></g>`, 1.15);
  let knit = "";
  for (let i = 0; i < 5; i++) { const xx = 76 + i * 9; knit += `<path d="M${xx},212 l3,4 l3,-4"/><path d="M${xx - 6},238 l3,4 l3,-4"/>`; }
  s += `<g opacity=".5">` + K.I(knit, .7) + `</g>`;
  let fringe = "";
  for (let i = 0; i < 4; i++) fringe += `<path d="M${f(26 - i * .4)},${f(234 + i * 6)} l-8,${f(1.5 + i * .4)}"/>`;
  for (let i = 0; i < 3; i++) fringe += `<path d="M${f(34 - i * .4)},${f(210 + i * 6)} l-8,${f(1 + i * .4)}"/>`;
  s += K.I(fringe, .9);

  // чашка: ободок чуть раскрыт, чтобы видна была гладь кофе
  const x = 200, y = 150, w = 118, h = w * .7, ry = 19;
  const body = `M${x - w / 2},${y} C${x - w / 2},${f(y + h * .8)} ${f(x - w * .3)},${f(y + h)} ${x},${f(y + h)} C${f(x + w * .3)},${f(y + h)} ${x + w / 2},${f(y + h * .8)} ${x + w / 2},${y}`;
  const shade = `M${f(x + w * .16)},${y} L${x + w / 2},${y} C${x + w / 2},${f(y + h * .8)} ${f(x + w * .32)},${f(y + h)} ${f(x + w * .1)},${f(y + h)}Z`;
  const handle = `M${f(x + w * .47)},${f(y + h * .18)} C${f(x + w * .8)},${f(y + h * .08)} ${f(x + w * .8)},${f(y + h * .66)} ${f(x + w * .34)},${f(y + h * .76)}`;
  s += K.W(`<ellipse cx="${x}" cy="${f(y + h + 3)}" rx="${f(w * .72)}" ry="${f(w * .11)}"/>`, WC.c1, .5);
  s += K.Ws(handle, WC.c1, w * .09, .6);
  s += K.W(`<path d="${body}Z"/><ellipse cx="${x}" cy="${y}" rx="${w / 2}" ry="${ry}"/>`, WC.c1, .45);
  s += K.W(`<path d="${shade}"/>`, WC.c2, .32);
  // гладь кофе — ровная, тёмная
  s += K.W(`<ellipse cx="${x}" cy="${y + 2}" rx="${w / 2 - 7}" ry="${ry - 5}"/>`, WC.c3, .9);
  // отражение месяца и мягкая дорожка света белилами
  s += K.Wf(`<ellipse cx="${x + 20}" cy="${y + 3}" rx="26" ry="5"/>`, WC.white, .38);
  s += `<path d="M${x + 8},${y + 1} Q${x + 23},${y + 13} ${x + 38},${y + 1} Q${x + 23},${y + 6} ${x + 8},${y + 1}Z" fill="${WC.white}" opacity=".92"/>`;
  s += `<path d="M${x - 30},${y + 9} h10 M${x - 16},${y + 10} h6" stroke="${WC.white}" stroke-width="1.1" stroke-linecap="round" opacity=".55"/>`;
  s += K.I(`<g transform="translate(1.6,-1.4)"><path d="${body}"/><ellipse cx="${x}" cy="${y}" rx="${w / 2}" ry="${ry}"/><path d="${handle}"/>` +
    `<path d="M${f(x - w * .7)},${f(y + h + 5)} Q${x},${f(y + h + w * .19)} ${f(x + w * .72)},${f(y + h + 3)}"/></g>`);
  // один медленный завиток пара
  s += K.Ws(`M${x - 6},${y - 14} c-12,-14 12,-22 2,-38 c-6,-10 6,-18 14,-22`, WC.c1, 7, .3);
  s += K.I(`<path d="M${x - 4},${y - 12} c-12,-14 12,-22 2,-38 c-6,-10 6,-18 14,-22"/>`, 1.3);
  s += K.splat(22, 6, 40, 70, 300, 200, WC.c2, 1.6);
  return s;
};
