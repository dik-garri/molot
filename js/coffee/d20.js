// День 20 — За дружбу с Богом (Ин 15:15: «Я назвал вас друзьями»). Образ: две чашки рядом, как за разговором;
// пар от них переплетается и складывается в одно сердце; на бумаге два пересекающихся следа от чашек.
COFFEE_ART[20] = (K, C) => {
  const { WC, cup, f } = C;
  let s = "";
  // два следа от чашек, пересекаются
  s += K.ring(116, 224, 44, .55) + K.ring(206, 228, 44, .55);
  // сердце из пара: заливка светлой размывкой
  const cx = 160, cy = 88, k = 40;
  const tip = [cx, cy + k * .9], cleft = [cx, cy - k * .38];
  const L = `C${f(cx - k * 1.35)},${f(cy + k * .05)} ${f(cx - k * .95)},${f(cy - k)} ${cleft[0]},${f(cleft[1])}`;
  const R = `C${f(cx + k * 1.35)},${f(cy + k * .05)} ${f(cx + k * .95)},${f(cy - k)} ${cleft[0]},${f(cleft[1])}`;
  s += K.B(`<path d="${C.heart(cx, cy, k * 2)}"/>`, WC.c1, .32);
  s += K.W(`<path d="${C.heart(cx, cy + 2, k * 1.6)}"/>`, WC.c1, .22);
  // две ленты пара: из левой чашки уходит в правую половину сердца, из правой — в левую; у острия они перекрещиваются
  const sL = `M134,166 C124,154 144,148 138,140 C133,133 146,130 ${tip[0]},${f(tip[1])} ${R}`;
  const sR = `M186,169 C196,157 176,151 182,143 C187,136 174,130 ${tip[0]},${f(tip[1])} ${L}`;
  s += K.Ws(sL, WC.c1, 10, .38) + K.Ws(sR, WC.c1, 10, .38);
  s += K.I(`<path d="${sL}" stroke-dasharray="22 5 34 4 400"/><path d="${sR}" stroke-dasharray="26 4 30 5 400"/>`, 1.3);
  // лёгкие отдельные струйки пара
  s += K.I(`<path d="M${cleft[0]},${f(cleft[1] - 3)} c-4,-6 4,-9 0,-14" stroke-width=".9"/><path d="M110,164 c-4,-7 3,-10 0,-17" stroke-width=".8"/><path d="M210,167 c4,-7 -3,-10 0,-17" stroke-width=".8"/>`, .9);
  // чашки, ручками наружу
  s += cup(K, 122, 174, 64, { dir: -1 });
  s += cup(K, 198, 177, 64, { dir: 1 });
  s += K.splat(20, 9, 30, 60, 300, 268, WC.c2);
  return s;
};
